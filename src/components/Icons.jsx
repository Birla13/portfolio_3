/** Shared <svg> wrapper: outline icons pass `stroke`, solid icons don't. */
function Svg({ size = 16, stroke, strokeWidth = 1.5, style, children }) {
  const paint = stroke
    ? { fill: "none", stroke: "currentColor", strokeWidth, strokeLinecap: "round", strokeLinejoin: "round" }
    : { fill: "currentColor" };
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} aria-hidden="true" style={style} {...paint}>
      {children}
    </svg>
  );
}

